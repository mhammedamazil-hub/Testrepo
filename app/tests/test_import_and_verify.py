"""Tests for the external-mesh import path and the standalone verifier/renderer.

The fixture is generated by tools/make_test_mesh.py: a checkerboard-textured
sphere. It is a *verifier fixture*, not a model output, and it is labelled as
such in its own glTF `generator` string.
"""
from __future__ import annotations

import importlib.util
import json
import struct
import sys
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from app.server.main import app                      # noqa: E402
from tools.verify_mesh import Glb, png_decode, render  # noqa: E402

FIXTURE = ROOT / "tools" / "fixtures" / "textured_sphere.glb"


def _build_fixture() -> Path:
    if not FIXTURE.exists():
        spec = importlib.util.spec_from_file_location("mkm", ROOT / "tools" / "make_test_mesh.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        module.build(FIXTURE, seg=24, ring=12)
    return FIXTURE


@pytest.fixture()
def client():
    return TestClient(app)


# --------------------------------------------------------------- verifier

def test_png_decoder_roundtrip():
    from tools.make_test_mesh import checker_png

    data = checker_png(64, 8)
    w, h, ch, px = png_decode(data)
    assert (w, h, ch) == (64, 64, 3)
    assert len(px) == 64 * 64 * 3
    # first pixel of a checkerboard is the "light" colour
    assert px[0:3] == bytes((235, 235, 240))


def test_glb_parse_detects_texture_and_uvs():
    glb = Glb(_build_fixture())
    summary = glb.summary()
    assert summary["problems"] == []
    assert summary["uv_mapped"] is True, "TEXCOORD_0 + baseColorTexture must be detected"
    assert "TEXCOORD_0" in summary["attributes"]
    assert summary["triangles"] > 0
    assert summary["images"][0]["width"] == 512


def test_glb_rejects_corrupt_files(tmp_path):
    good = _build_fixture().read_bytes()
    truncated = tmp_path / "trunc.glb"
    truncated.write_bytes(good[: len(good) // 2])
    with pytest.raises(ValueError, match="file size"):
        Glb(truncated)

    bad_magic = tmp_path / "magic.glb"
    bad_magic.write_bytes(b"XXXX" + good[4:])
    with pytest.raises(ValueError, match="magic"):
        Glb(bad_magic)


def test_renderer_produces_non_empty_images(tmp_path):
    glb = Glb(_build_fixture())
    files, stats = render(glb, tmp_path, frames=2, width=96, height=72)
    assert len(files) == 2
    assert stats["triangles_rendered"] > 0
    for f in files:
        w, h, ch, px = png_decode(f.read_bytes())
        assert (w, h) == (96, 72)
        # the object must actually be drawn: some pixels differ from the background
        bg = bytes((0x12, 0x16, 0x1D))
        assert any(px[i:i + 3] != bg for i in range(0, len(px), 3)), "render is blank"


# --------------------------------------------------------------- import API

def test_import_glb_roundtrip_is_byte_identical(client):
    raw = _build_fixture().read_bytes()
    r = client.post(
        "/api/import",
        files={"files": ("mesh.glb", raw, "model/gltf-binary")},
        data={"origin_note": "pytest fixture"},
    )
    assert r.status_code == 201, r.text
    job = r.json()
    assert job["origin"] == "external_import"
    assert job["provider"] == "external_import"
    assert "not generated by this server" in job["message"]
    assert job["metadata"]["glb"]["uv_mapped"] is True

    back = client.get(job["files"]["glb"])
    assert back.status_code == 200
    assert back.content == raw, "import must store the original bytes untouched"
    assert back.headers["content-type"] == "model/gltf-binary"


def test_import_rejects_truncated_glb(client):
    raw = _build_fixture().read_bytes()[:100]
    r = client.post("/api/import", files={"files": ("broken.glb", raw, "model/gltf-binary")})
    assert r.status_code == 422
    assert "structural validation" in r.json()["detail"]


def test_import_rejects_non_mesh(client):
    r = client.post("/api/import", files={"files": ("notes.txt", b"hello", "text/plain")})
    assert r.status_code == 415


def test_import_obj_with_material_siblings(client):
    obj = b"# test\nv 0 0 0\nv 1 0 0\nv 0 1 0\nvt 0 0\nvt 1 0\nvt 0 1\nf 1/1 2/2 3/3\nusemtl mat\nmtllib m.mtl\n"
    mtl = b"newmtl mat\nmap_Kd tex.png\n"
    png = b"\x89PNG\r\n\x1a\n" + b"0" * 40
    r = client.post(
        "/api/import",
        files=[
            ("files", ("mesh.obj", obj, "model/obj")),
            ("files", ("m.mtl", mtl, "text/plain")),
            ("files", ("tex.png", png, "image/png")),
        ],
    )
    assert r.status_code == 201, r.text
    job = r.json()
    assert job["files"]["obj"].endswith("/obj")
    extras = [k for k in job["files"] if k.startswith("extra_")]
    assert len(extras) == 2, f"mtl + texture must be retained, got {list(job['files'])}"


def test_import_does_not_mark_inference(client):
    """An imported mesh must never be reported as inference by this server."""
    r = client.post("/api/import", files={"files": ("m.glb", _build_fixture().read_bytes(), "model/gltf-binary")})
    job = r.json()
    assert job["origin"] != "inference"
    assert job["simulated"] is False
