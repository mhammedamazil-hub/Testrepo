/* Actual Chromium touch events, mobile viewport, real Godot Web runtime.
   Emulation is NOT a physical-phone or 60 FPS certification. */
const path=require('path'),fs=require('fs');
const root=path.resolve(__dirname,'../..');
const {chromium:playwright}=require(path.join(root,'.cache/browser/node_modules/playwright-core'));
(async()=>{
 const {default:chromium}=await import(path.join(root,'.cache/browser/node_modules/@sparticuz/chromium/build/index.js'));
 const executablePath=await chromium.executablePath();
 const libraries=[path.join(root,'.cache/browser-runtime/usr/lib/x86_64-linux-gnu'),path.join(root,'.cache/software-graphics/runtime/usr/lib/x86_64-linux-gnu'),'/tmp',process.env.LD_LIBRARY_PATH||''].join(':');
 const browser=await playwright.launch({executablePath,env:{...process.env,LD_LIBRARY_PATH:libraries},args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'],headless:true});
 const context=await browser.newContext({viewport:{width:932,height:430},deviceScaleFactor:1,isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/153.0.0.0 Mobile Safari/537.36'});
 const page=await context.newPage(),cdp=await context.newCDPSession(page);
 const out=path.join(root,'docs/game');fs.mkdirSync(out,{recursive:true});
 const errors=[],checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{console.log(m.type(),m.text());if(m.type()==='error')errors.push(m.text());});
 const check=(name,passed)=>{checks.push({name,passed});console.log(passed?'PASS':'FAIL',name);if(!passed)throw Error(name);};
 const telemetry=()=>page.evaluate(()=>window.alpineTelemetry);
 const wait=async(fn,arg,timeout=180000)=>page.waitForFunction(fn,arg,{timeout});
 await page.goto(process.env.GAME_URL||'http://127.0.0.1:3000',{waitUntil:'domcontentloaded',timeout:60000});
 await wait(()=>window.alpineReady&&window.alpineTelemetry);
 const initial=await telemetry();
 check('Mobile touch controls auto-detected',initial.touch_enabled===true);
 check('Native 1920x1080 canvas retained',initial.render_size[0]===1920&&initial.render_size[1]===1080);
 const bounds=await page.locator('#canvas').boundingBox();
 const point=(id,x,y)=>({id,x:bounds.x+x/1920*bounds.width,y:bounds.y+y/1080*bounds.height,radiusX:5,radiusY:5,force:1});
 const send=(type,points=[])=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points});
 const tap=async(x,y)=>{await send('touchStart',[point(0,x,y)]);await page.waitForTimeout(1500);await send('touchEnd');};
 async function canvas(name){
   const png=await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>resolve(document.getElementById('canvas').toDataURL('image/png')))));
   fs.writeFileSync(path.join(out,name),Buffer.from(png.split(',')[1],'base64'));
 }
 await canvas('mobile-menu-1080p.png');
 await tap(300,790);
 console.log("AFTER BEGIN TOUCH",await telemetry(),bounds);
 await wait(()=>window.alpineTelemetry?.playing&&!window.alpineTelemetry?.paused);
 check('Touch begins the actual game',true);
 if(process.env.REALISM_CAPTURE_ONLY==='1'){
   await canvas('mobile-walking-1080p.png');
   await tap(1535,710);
   await wait(()=>window.alpineTelemetry?.driving);
   await canvas('mobile-driving-1080p.png');
   const physical=await cdp.send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
   fs.writeFileSync(path.join(out,'mobile-landscape-browser.png'),Buffer.from(physical.data,'base64'));
   console.log('FINAL_REALISM_CAPTURE_PASS',await telemetry());
   await browser.close();return;
 }
 const walkStart=(await telemetry()).player;
 await send('touchStart',[point(0,235,840)]);
 await send('touchMove',[point(0,235,680)]);
 const yawStart=(await telemetry()).camera_yaw;
 await send('touchStart',[point(0,235,680),point(1,1100,440)]);
 await send('touchMove',[point(0,235,680),point(1,1200,440)]);
 await wait(y=>window.alpineTelemetry?.touch_fingers===2&&Math.abs(window.alpineTelemetry.camera_yaw-y)>.1,yawStart);
 check('Two-finger movement plus camera orbit',true);
 await wait(p=>{const t=window.alpineTelemetry;return Math.hypot(t.player[0]-p[0],t.player[2]-p[2])>.7;},walkStart);
 await send('touchEnd');
 await wait(()=>window.alpineTelemetry?.touch_fingers===0&&!window.alpineTelemetry?.touch_actions.forward);
 const walking=await telemetry();
 check('Joystick walks and releases without stuck input',true);
 await canvas('mobile-walking-1080p.png');
 await tap(1510,200);
 await tap(1535,710);
 await wait(()=>window.alpineTelemetry?.driving);
 check('Touch ENTER takes the wheel',true);
 const carStart=(await telemetry()).car;
 await send('touchStart',[point(0,1760,740),point(1,235,840)]);
 await send('touchMove',[point(0,1760,740),point(1,285,840)]);
 await wait(p=>{const t=window.alpineTelemetry;return t.driving&&Math.hypot(t.car[0]-p[0],t.car[2]-p[2])>3;},carStart);
 const driving=await telemetry();
 check('Multi-touch GAS and steering drive physical car',true);
 await send('touchEnd');
 await send('touchStart',[point(0,1740,945)]);
 await wait(()=>Math.abs(window.alpineTelemetry?.speed_mps??10)<.1);
 await send('touchEnd');
 check('Touch BRAKE stops car',true);
 await canvas('mobile-driving-1080p.png');
 const physical=await cdp.send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 fs.writeFileSync(path.join(out,'mobile-landscape-browser.png'),Buffer.from(physical.data,'base64'));
 await tap(1535,710);
 await wait(()=>window.alpineTelemetry?.driving===false);
 check('Touch EXIT returns to walking',true);
 await send('touchStart',[point(0,235,680)]);
 await wait(()=>window.alpineTelemetry?.touch_fingers>0);
 await send('touchCancel');
 await wait(()=>window.alpineTelemetry?.touch_fingers===0&&!window.alpineTelemetry?.touch_actions.forward);
 check('Browser touch cancellation releases controls',true);
 await tap(1760,200);
 await wait(()=>window.alpineTelemetry?.paused);
 check('Touch PAUSE opens pause menu',true);
 await tap(300,790);
 await wait(()=>window.alpineTelemetry?.paused===false);
 check('Touch resumes from pause menu',true);
 await send('touchStart',[point(0,235,680)]);
 await wait(()=>window.alpineTelemetry?.touch_fingers>0);
 await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
 await wait(()=>window.alpineTelemetry?.paused===true&&window.alpineTelemetry?.touch_fingers===0);
 await send('touchEnd');
 check('Browser focus loss pauses and releases held touch',true);
 await page.setViewportSize({width:430,height:932});
 check('Portrait orientation shows landscape guidance',await page.locator('#rotate').isVisible());
 await page.setViewportSize({width:932,height:430});
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await tap(300,790);
 await wait(()=>window.alpineTelemetry?.paused===false);
 const final=await telemetry();
 const gpu=await page.evaluate(()=>{const c=document.getElementById('canvas'),g=c.getContext('webgl2'),x=g.getExtension('WEBGL_debug_renderer_info');return {renderer:g.getParameter(x.UNMASKED_RENDERER_WEBGL),canvas:[c.width,c.height]};});
 check('No browser/runtime errors',errors.length===0);
 const report={status:'MOBILE_BROWSER_GAMEPLAY_PASS',scope:'Chromium mobile emulation with real CDP touch events; CPU SwiftShader, not a physical device or hardware performance certificate',viewport:[932,430],checks,initial,walking,driving,final,gpu,console_errors:errors,distance_driven_meters:Math.hypot(driving.car[0]-carStart[0],driving.car[2]-carStart[2]),physical_phone_tested:false,target_60fps_verified:false};
 fs.writeFileSync(path.join(out,'mobile-browser-validation.json'),JSON.stringify(report,null,2)+'\n');
 console.log('MOBILE_BROWSER_GAMEPLAY_PASS',JSON.stringify(report));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
